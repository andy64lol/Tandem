use std::{
    env, fs,
    io::IsTerminal,
    path::{Path, PathBuf},
    process,
    thread,
    time::Duration,
};

use tandem::compiler::{self, Diagnostic, Severity};
use tandem::target::LuaTarget;
use tandem::{cache, runtime};

const GENERATED_PREFIX: &str = "-- Generated by Tandem ";

/// Lua runner appended by `tandem test`.
const TEST_RUNNER: &str = r#"
local __tdm_tests = __tdm_tests or {}
local __tdm_names = {}
for name in pairs(__tdm_tests) do
    __tdm_names[#__tdm_names + 1] = name
end
table.sort(__tdm_names)
local __tdm_passed, __tdm_failed = 0, 0
for _, name in ipairs(__tdm_names) do
    local ok, err = pcall(__tdm_tests[name])
    if ok then
        print("ok   " .. name)
        __tdm_passed = __tdm_passed + 1
    else
        print("FAIL " .. name .. ": " .. tostring(err))
        __tdm_failed = __tdm_failed + 1
    end
end
print(string.format("%d passed, %d failed", __tdm_passed, __tdm_failed))
if __tdm_failed > 0 then
    error(string.format("%d test(s) failed", __tdm_failed), 0)
end
"#;

fn paint(text: &str, code: &str, colored: bool) -> String {
    if colored {
        format!("\x1b[{code}m{text}\x1b[0m")
    } else {
        text.to_string()
    }
}

fn status(label: &str, message: impl std::fmt::Display) {
    let label = format!("{label:>12}");
    println!(
        "{} {message}",
        paint(&label, "1;32", std::io::stdout().is_terminal())
    );
}

fn report(diagnostics: &[Diagnostic], path: &Path) {
    let colored = std::io::stderr().is_terminal();
    for (index, diagnostic) in diagnostics.iter().enumerate() {
        if index > 0 {
            eprintln!();
        }
        let code = match diagnostic.severity {
            Severity::Error => "1;31",
            Severity::Warning => "1;33",
        };
        let label = format!("{}:", diagnostic.severity.label());
        eprintln!("{} {}", paint(&label, code, colored), diagnostic.message);
        let location = match (diagnostic.line, diagnostic.column) {
            (Some(line), Some(column)) => {
                format!("{}:{line}:{column}", path.display())
            }
            _ => path.display().to_string(),
        };
        eprintln!(" {} {}", paint("-->", "1;34", colored), location);
    }
}

fn fail(message: impl std::fmt::Display) -> ! {
    eprintln!(
        "{} {message}",
        paint("error:", "1;31", std::io::stderr().is_terminal())
    );
    process::exit(1)
}

fn usage() -> ! {
    eprintln!(
        "Usage: tandem [--memory-limit <bytes>] [--instruction-limit <count>] [--sandbox] [--target <lua5.1|lua5.2|lua5.3|lua5.4>] <input.tdm|script.lua> [output.lua or script arguments...]\n       tandem [options] --check <input.tdm>\n       tandem --version\n       tandem fmt <input.tdm>\n       tandem repl\n       tandem lsp\n       tandem dap\n       tandem new <name>\n       tandem build\n       tandem run [--watch] [script arguments...]\n       tandem test [input.tdm]\n       tandem coverage [input.tdm]\n       tandem profile [input.tdm]\n       tandem add <name> [git-url] [--tag <tag>]\n       tandem pkg install [project-dir]"
    );
    process::exit(2)
}

fn check_output(path: &Path) -> Result<(), String> {
    if !path.exists() {
        return Ok(());
    }
    if path.is_dir() {
        return Err(format!(
            "cannot write {}: it is a directory",
            path.display()
        ));
    }
    let existing = fs::read_to_string(path)
        .map_err(|error| format!("cannot verify {}: {error}", path.display()))?;
    if existing.starts_with(GENERATED_PREFIX) {
        Ok(())
    } else {
        Err(format!(
            "refusing to overwrite {}: the file was not generated by Tandem",
            path.display()
        ))
    }
}

fn write_output(path: &Path, source: &str) -> Result<(), String> {
    check_output(path)?;
    fs::write(path, source).map_err(|error| format!("cannot write {}: {error}", path.display()))
}

/// The default entry point of a Tandem project rooted at `root`.
fn project_entry(root: &Path) -> PathBuf {
    for candidate in ["src/main.tdm", "src/lib.tdm", "main.tdm"] {
        let path = root.join(candidate);
        if path.exists() {
            return path;
        }
    }
    fail("no entry point found (expected src/main.tdm or main.tdm)".to_string());
}

/// The project name from `tandem.config`, falling back to `main`.
fn project_name(root: &Path) -> String {
    fs::read_to_string(root.join("tandem.config"))
        .ok()
        .and_then(|contents| {
            contents.lines().find_map(|line| {
                let line = line.trim();
                line.strip_prefix("name")
                    .and_then(|rest| rest.split_once('='))
                    .map(|(_, value)| value.trim().trim_matches('"').to_string())
            })
        })
        .unwrap_or_else(|| "main".to_string())
}

/// Compiles `entry`, returning the Lua source and its directory.
fn compile_file(entry: &Path) -> (String, PathBuf) {
    status("Compiling", entry.display());
    let source = fs::read_to_string(entry)
        .unwrap_or_else(|error| fail(format!("cannot read {}: {error}", entry.display())));
    let parent = entry
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or(Path::new("."))
        .to_path_buf();
    let name = entry
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .into_owned();
    let lua_source = compiler::compile_with_dir_named(&source, &parent, &name)
        .unwrap_or_else(|diagnostics| {
            report(&diagnostics, entry);
            process::exit(1)
        });
    (lua_source, parent)
}

/// Builds a project entry into `output_dir`, reusing a cached result when the
/// sources are unchanged.  Returns the generated `.lua` path.
fn build_project(
    entry: &Path,
    name: &str,
    output_dir: &Path,
    target: Option<LuaTarget>,
    use_cache: bool,
) -> PathBuf {
    fs::create_dir_all(output_dir)
        .unwrap_or_else(|error| fail(format!("cannot create target dir: {error}")));
    let output_path = output_dir.join(format!("{name}.lua"));
    let cache_path = output_dir.join(format!(".{name}.fingerprint"));
    let source_root = entry
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let fingerprint = cache::fingerprint(source_root);

    if use_cache && output_path.exists() && cache::is_fresh(&cache_path, fingerprint) {
        status("Fresh", output_path.display());
        return output_path;
    }

    let (lua_source, _) = compile_file(entry);
    let lua_source = match target {
        Some(target) => target.transform(&lua_source),
        None => lua_source,
    };
    if let Err(error) = fs::write(&output_path, &lua_source) {
        fail(format!("cannot write {}: {error}", output_path.display()));
    }
    let _ = cache::store(&cache_path, fingerprint);
    status(
        "Finished",
        format!("{} -> {}", entry.display(), output_path.display()),
    );
    output_path
}

fn print_coverage(source: &str, instrumentation: &runtime::Instrumentation) {
    let executable = runtime::executable_lines(source);
    let covered = executable
        .iter()
        .filter(|line| instrumentation.executed.contains_key(line))
        .count();
    let total = executable.len();
    let percent = if total == 0 {
        100.0
    } else {
        covered as f64 / total as f64 * 100.0
    };
    println!();
    println!("Coverage: {covered}/{total} lines ({percent:.1}%)");
    let mut uncovered = executable
        .into_iter()
        .filter(|line| !instrumentation.executed.contains_key(line))
        .collect::<Vec<_>>();
    if !uncovered.is_empty() {
        uncovered.sort_unstable();
        let ranges = uncovered
            .iter()
            .map(usize::to_string)
            .collect::<Vec<_>>()
            .join(", ");
        println!("Uncovered lines: {ranges}");
    }
}

fn print_profile(profile: &runtime::Profile) {
    println!();
    let total = profile.total_ns.max(1);
    println!("Profile ({} samples, {:.3} ms observed)", profile.samples.values().sum::<usize>(), total as f64 / 1_000_000.0);
    let mut rows = profile
        .time_ns
        .iter()
        .map(|(line, time)| (*line, *time))
        .collect::<Vec<_>>();
    rows.sort_by(|left, right| right.1.cmp(&left.1));
    for (line, time) in rows.into_iter().take(10) {
        println!(
            "  line {line:>5}: {:>6.2}% ({:.3} ms)",
            time as f64 / total as f64 * 100.0,
            time as f64 / 1_000_000.0
        );
    }
}

fn main() {
    let mut args: Vec<String> = env::args().skip(1).collect();
    if args.is_empty() {
        usage();
    }

    let mut config = runtime::RuntimeConfig::default();
    let mut target: Option<LuaTarget> = None;
    let mut watch = false;
    let mut index = 0;
    while index < args.len() {
        match args[index].as_str() {
            "--memory-limit" | "--instruction-limit" | "--target" => {
                if index + 1 >= args.len() {
                    usage();
                }
                let option = args.remove(index);
                let value = args.remove(index);
                match option.as_str() {
                    "--memory-limit" => {
                        config.memory_limit = Some(value.parse().unwrap_or_else(|_| {
                            fail(format!("invalid memory limit '{value}': expected bytes"))
                        }));
                    }
                    "--instruction-limit" => {
                        config.instruction_limit = Some(value.parse().unwrap_or_else(|_| {
                            fail(format!(
                                "invalid instruction limit '{value}': expected a number"
                            ))
                        }));
                    }
                    _ => {
                        target = Some(LuaTarget::parse(&value).unwrap_or_else(|| {
                            fail(format!(
                                "invalid target '{value}': expected lua5.1, lua5.2, lua5.3 or lua5.4"
                            ))
                        }));
                    }
                }
            }
            "--sandbox" => {
                config.sandbox = true;
                args.remove(index);
            }
            "--watch" | "--hot-reload" => {
                watch = true;
                args.remove(index);
            }
            _ => index += 1,
        }
    }
    if args.is_empty() {
        usage();
    }

    if args[0] == "--version" || args[0] == "-V" {
        if args.len() != 1 {
            usage();
        }
        println!("tandem {}", env!("CARGO_PKG_VERSION"));
        return;
    }

    if args[0] == "fmt" {
        if args.len() != 2 {
            usage();
        }
        let input_path = Path::new(&args[1]);
        let source = fs::read_to_string(input_path)
            .unwrap_or_else(|error| fail(format!("cannot read {}: {error}", input_path.display())));
        let formatted = tandem::compiler::formatter::format_source(&source)
            .unwrap_or_else(|error| fail(error));
        if let Err(error) = fs::write(input_path, formatted) {
            fail(format!("cannot write {}: {error}", input_path.display()));
        }
        status("Formatted", input_path.display());
        return;
    }

    if args[0] == "repl" {
        if args.len() != 1 {
            usage();
        }
        tandem::repl::run();
        return;
    }

    if args[0] == "lsp" {
        if args.len() != 1 {
            usage();
        }
        tandem::lsp::serve();
        return;
    }

    if args[0] == "dap" {
        if args.len() != 1 {
            usage();
        }
        tandem::dap::serve();
        return;
    }

    if args[0] == "new" {
        if args.len() != 2 {
            usage();
        }
        let path_arg = &args[1];
        let root = Path::new(path_arg);
        let name = root
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or(path_arg)
            .to_string();
        if root.exists() {
            fail(format!("directory '{name}' already exists"));
        }
        fs::create_dir_all(root.join("src"))
            .unwrap_or_else(|error| fail(format!("cannot create project: {error}")));
        let config = format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\n\n[deps]\n");
        fs::write(root.join("tandem.config"), config)
            .unwrap_or_else(|error| fail(format!("cannot write tandem.config: {error}")));
        fs::write(
            root.join("src").join("main.tdm"),
            "fn main() -> void {\n    print(\"Hello, world!\");\n}\n\nmain();\n",
        )
        .unwrap_or_else(|error| fail(format!("cannot write main.tdm: {error}")));
        status("Created", name);
        return;
    }

    if args[0] == "add" {
        if args.len() < 2 {
            usage();
        }
        let name = args[1].clone();
        let mut git = None;
        let mut tag = None;
        let mut index = 2;
        while index < args.len() {
            match args[index].as_str() {
                "--tag" => {
                    if index + 1 >= args.len() {
                        usage();
                    }
                    tag = Some(args[index + 1].clone());
                    index += 2;
                }
                other if git.is_none() => {
                    git = Some(other.to_string());
                    index += 1;
                }
                _ => usage(),
            }
        }
        status("Adding", &name);
        if let Err(error) =
            tandem::packages::add(".", &name, git.as_deref(), tag.as_deref())
        {
            fail(error);
        }
        status("Finished", format!("added package '{name}'"));
        return;
    }

    if args[0] == "build" || args[0] == "run" {
        let is_run = args[0] == "run";
        if !is_run && args.len() > 1 {
            usage();
        }
        let script_args: Vec<String> = if is_run {
            args[1..].to_vec()
        } else {
            Vec::new()
        };
        let root = Path::new(".");
        let entry = project_entry(root);
        let name = project_name(root);
        let output_dir = match target {
            Some(target) => root.join("target").join(target.name()).join("debug"),
            None => root.join("target").join("debug"),
        };

        if is_run && watch {
            let source_root = entry
                .parent()
                .filter(|parent| !parent.as_os_str().is_empty())
                .unwrap_or(Path::new("."));
            let mut last = cache::fingerprint(source_root);
            loop {
                let output =
                    build_project(&entry, &name, &output_dir, target, true);
                if let Err(error) =
                    runtime::run_file_with_config(&output, &script_args, &config)
                {
                    eprintln!("error: {error}");
                }
                loop {
                    thread::sleep(Duration::from_millis(400));
                    let fingerprint = cache::fingerprint(source_root);
                    if fingerprint != last {
                        last = fingerprint;
                        break;
                    }
                }
            }
        }

        let output = build_project(&entry, &name, &output_dir, target, true);
        if is_run {
            runtime::run_file_with_config(&output, &script_args, &config)
                .unwrap_or_else(|error| fail(error));
        }
        return;
    }

    if args[0] == "test" {
        if args.len() > 2 {
            usage();
        }
        let entry = args
            .get(1)
            .map(PathBuf::from)
            .unwrap_or_else(|| project_entry(Path::new(".")));
        let (lua_source, parent) = compile_file(&entry);
        let mut program = lua_source;
        program.push_str(TEST_RUNNER);
        let name = format!("{} (tests)", entry.display());
        runtime::run_source_with_config(&program, &name, &[], &parent, &config)
            .unwrap_or_else(|error| fail(error));
        return;
    }

    if args[0] == "coverage" || args[0] == "profile" {
        if args.len() > 2 {
            usage();
        }
        let entry = args
            .get(1)
            .map(PathBuf::from)
            .unwrap_or_else(|| project_entry(Path::new(".")));
        let (lua_source, parent) = compile_file(&entry);
        let name = entry.to_string_lossy();
        if args[0] == "coverage" {
            let instrumentation = runtime::run_source_with_instrumentation(
                &lua_source, &name, &[], &parent, &config,
            )
            .unwrap_or_else(|error| fail(error));
            print_coverage(&lua_source, &instrumentation);
        } else {
            let profile =
                runtime::run_source_with_profile(&lua_source, &name, &[], &parent, &config)
                    .unwrap_or_else(|error| fail(error));
            print_profile(&profile);
        }
        return;
    }

    if args[0] == "pkg" {
        if args.len() < 2 || args.len() > 3 || args[1] != "install" {
            usage();
        }
        let root = args
            .get(2)
            .map(PathBuf::from)
            .unwrap_or_else(|| PathBuf::from("."));
        status("Installing", root.display());
        if let Err(error) = tandem::packages::install(&root) {
            fail(error);
        }
        status(
            "Finished",
            format!("installed Lua packages in {}", root.display()),
        );
        return;
    }

    if args[0] == "--check" {
        if args.len() != 2 {
            usage();
        }
        let input_path = Path::new(&args[1]);
        status("Checking", input_path.display());
        let source = fs::read_to_string(input_path)
            .unwrap_or_else(|error| fail(format!("cannot read {}: {error}", input_path.display())));
        let parent = input_path
            .parent()
            .filter(|parent| !parent.as_os_str().is_empty())
            .unwrap_or(Path::new("."));
        compiler::compile_with_dir_named(
            &source,
            parent,
            &input_path.file_name().unwrap_or_default().to_string_lossy(),
        )
        .unwrap_or_else(|diagnostics| {
            report(&diagnostics, input_path);
            process::exit(1)
        });
        status("Finished", input_path.display());
        return;
    }

    let input_path = Path::new(&args[0]);
    if input_path
        .extension()
        .is_some_and(|extension| extension == "lua")
    {
        status("Running", input_path.display());
        runtime::run_file_with_config(input_path, &args[1..], &config)
            .unwrap_or_else(|error| fail(error));
        return;
    }

    if args.len() > 2 {
        usage();
    }
    let output_path = args.get(1).map(PathBuf::from).unwrap_or_else(|| {
        let mut path = input_path.to_path_buf();
        path.set_extension("lua");
        path
    });
    if let Err(error) = check_output(&output_path) {
        fail(error);
    }

    status("Compiling", input_path.display());
    let source = fs::read_to_string(input_path)
        .unwrap_or_else(|error| fail(format!("cannot read {}: {error}", input_path.display())));
    let parent = input_path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let lua_source = compiler::compile_with_dir_named(
        &source,
        parent,
        &input_path.file_name().unwrap_or_default().to_string_lossy(),
    )
    .unwrap_or_else(|diagnostics| {
        report(&diagnostics, input_path);
        process::exit(1)
    });
    let lua_source = match target {
        Some(target) => target.transform(&lua_source),
        None => lua_source,
    };

    if let Err(error) = write_output(&output_path, &lua_source) {
        fail(error);
    }
    status("Finished", output_path.display());
    runtime::run_file_with_config_in(&output_path, &[], parent, &config)
        .unwrap_or_else(|error| fail(error));
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};

    fn temp_file(name: &str) -> PathBuf {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let id = NEXT.fetch_add(1, Ordering::SeqCst);
        env::temp_dir().join(format!("tandem-{}-{id}-{name}", process::id()))
    }

    #[test]
    fn rejects_output_not_generated_by_tandem() {
        let path = temp_file("out.lua");
        fs::write(&path, "print('handwritten')\n").unwrap();
        let error = check_output(&path).unwrap_err();
        assert!(error.contains("was not generated by Tandem"));
        fs::remove_file(&path).unwrap();
    }

    #[test]
    fn allows_overwriting_generated_output() {
        let path = temp_file("out.lua");
        fs::write(
            &path,
            "-- Generated by Tandem 0.2.0. Do not edit this file.\nprint('old')\n",
        )
        .unwrap();
        check_output(&path).unwrap();
        write_output(
            &path,
            "-- Generated by Tandem 0.2.0. Do not edit this file.\nprint('new')\n",
        )
        .unwrap();
        assert!(fs::read_to_string(&path).unwrap().contains("print('new')"));
        fs::remove_file(&path).unwrap();
    }
}
